import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { ActivatedRoute, RouterLink } from '@angular/router';
import { firstValueFrom } from 'rxjs';

import { FlowFieldType, FlowService } from '../../proxy/flows';
import { ArTopbar } from '../../layout/topbar';
import { ArButton } from '../../ui';

interface FieldRow {
  name: string;
  label: string;
  fieldType: FlowFieldType;
  required: boolean;
  options: string;
}
interface ScreenRow {
  screenId: string;
  title: string;
  webhookUrl: string;
  fields: FieldRow[];
}

const FIELD_TYPES = [
  { value: FlowFieldType.TextInput, label: 'Text' },
  { value: FlowFieldType.TextArea, label: 'Paragraph' },
  { value: FlowFieldType.Dropdown, label: 'Dropdown' },
  { value: FlowFieldType.RadioButtons, label: 'Radio buttons' },
  { value: FlowFieldType.CheckboxGroup, label: 'Checkboxes' },
  { value: FlowFieldType.DatePicker, label: 'Date' },
  { value: FlowFieldType.OptIn, label: 'Opt-in' },
];

/**
 * Tenant-facing flow designer (M08-6). Screens and fields, not raw JSON — the Flow
 * JSON is generated by the API from what is captured here.
 */
@Component({
  selector: 'ar-flow-designer',
  imports: [RouterLink, ArTopbar, ArButton],
  changeDetection: ChangeDetectionStrategy.OnPush,
  templateUrl: './flow-designer.html',
  styleUrl: './flow-designer.scss',
})
export class ArFlowDesigner {
  private readonly api = inject(FlowService);
  private readonly route = inject(ActivatedRoute);

  protected readonly fieldTypes = FIELD_TYPES;
  protected readonly FT = FlowFieldType;

  protected readonly flowId = signal('');
  protected readonly name = signal('');
  protected readonly channelId = signal('');
  protected readonly dataEndpointUrl = signal('');
  protected readonly definitionJson = signal('{}');
  protected readonly screens = signal<ScreenRow[]>([]);
  protected readonly loading = signal(true);
  protected readonly saving = signal(false);
  protected readonly error = signal<string | null>(null);
  protected readonly savedJson = signal('');

  protected readonly needsOptions = (t: FlowFieldType) =>
    t === FlowFieldType.Dropdown ||
    t === FlowFieldType.RadioButtons ||
    t === FlowFieldType.CheckboxGroup;

  constructor() {
    this.flowId.set(this.route.snapshot.paramMap.get('id') ?? '');
    void this.load();
  }

  private async load(): Promise<void> {
    this.loading.set(true);
    try {
      const dto = await firstValueFrom(this.api.get(this.flowId()));
      this.name.set(dto.name ?? '');
      this.channelId.set(dto.channelId ?? '');
      this.dataEndpointUrl.set(dto.dataEndpointUrl ?? '');
      this.definitionJson.set(dto.definitionJson ?? '{}');
      this.savedJson.set(dto.definitionJson ?? '');
      this.screens.set(
        (dto.screens ?? [])
          .slice()
          .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
          .map((s) => ({
            screenId: s.screenId ?? '',
            title: s.title ?? '',
            webhookUrl: s.webhookUrl ?? '',
            fields: (s.fields ?? [])
              .slice()
              .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
              .map((f) => ({
                name: f.name ?? '',
                label: f.label ?? '',
                fieldType: f.fieldType ?? FlowFieldType.TextInput,
                required: f.required ?? false,
                options: f.optionsText ?? '',
              })),
          })),
      );
    } catch {
      this.error.set('Could not load this flow.');
    } finally {
      this.loading.set(false);
    }
  }

  protected addScreen(): void {
    this.screens.update((list) => [
      ...list,
      { screenId: `SCREEN_${list.length + 1}`, title: 'New screen', webhookUrl: '', fields: [] },
    ]);
  }
  protected removeScreen(i: number): void {
    this.screens.update((l) => l.filter((_, idx) => idx !== i));
  }
  protected setScreen(i: number, key: keyof ScreenRow, value: string): void {
    this.screens.update((l) => l.map((s, idx) => (idx === i ? { ...s, [key]: value } : s)));
  }
  protected addField(si: number): void {
    this.screens.update((l) =>
      l.map((s, idx) =>
        idx === si
          ? {
              ...s,
              fields: [
                ...s.fields,
                {
                  name: `field_${s.fields.length + 1}`,
                  label: 'New field',
                  fieldType: FlowFieldType.TextInput,
                  required: false,
                  options: '',
                },
              ],
            }
          : s,
      ),
    );
  }
  protected removeField(si: number, fi: number): void {
    this.screens.update((l) =>
      l.map((s, idx) => (idx === si ? { ...s, fields: s.fields.filter((_, x) => x !== fi) } : s)),
    );
  }
  protected setField(
    si: number,
    fi: number,
    key: keyof FieldRow,
    value: string | number | boolean,
  ): void {
    this.screens.update((l) =>
      l.map((s, idx) =>
        idx === si
          ? { ...s, fields: s.fields.map((f, x) => (x === fi ? { ...f, [key]: value } : f)) }
          : s,
      ),
    );
  }

  protected async save(): Promise<void> {
    this.saving.set(true);
    this.error.set(null);
    try {
      const updated = await firstValueFrom(
        this.api.update(this.flowId(), {
          name: this.name().trim(),
          channelId: this.channelId(),
          definitionJson: this.definitionJson(),
          dataEndpointUrl: this.dataEndpointUrl().trim() || null,
          // Once there are screens the designer owns the JSON and rebuilds it from
          // them; an empty designer leaves whatever JSON the flow already had.
          generateDefinitionFromScreens: this.screens().length > 0,
          screens: this.screens().map((s, i) => ({
            screenId: s.screenId.trim(),
            title: s.title.trim(),
            order: i,
            webhookUrl: s.webhookUrl.trim() || null,
            fields: s.fields.map((f, fi) => ({
              name: f.name.trim(),
              label: f.label.trim(),
              fieldType: f.fieldType,
              required: f.required,
              order: fi,
              optionsText: this.needsOptions(f.fieldType) ? f.options.trim() || null : null,
            })),
          })),
        }),
      );
      this.savedJson.set(updated.definitionJson ?? '');
      this.definitionJson.set(updated.definitionJson ?? '{}');
    } catch (e: unknown) {
      this.error.set(e instanceof Error ? e.message : 'Could not save the flow.');
    } finally {
      this.saving.set(false);
    }
  }

  protected readonly prettyJson = computed(() => {
    try {
      return JSON.stringify(JSON.parse(this.savedJson() || '{}'), null, 2);
    } catch {
      return this.savedJson();
    }
  });
}
