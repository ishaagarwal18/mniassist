/**
 * A GSTR-2B JSON for a busy month runs to a few megabytes. It travels as an escaped string, about 15% larger, and the
 * server takes requests up to 30 MB, so files are kept under 20 MB.
 */
export const GSTR2B_MAX_BYTES = 20 * 1024 * 1024;
const PAGE = 50;

export function matchLabel(match: Gstr2bLineMatch): { label: string; tone: ChipTone } {
  switch (match) {
    case Gstr2bLineMatch.Matched:
      return { label: 'Matched', tone: 'good' };
    case Gstr2bLineMatch.TaxMismatch:
      return { label: 'Tax differs', tone: 'amber' };
    case Gstr2bLineMatch.NotInBooks:
      return { label: 'Not in books', tone: 'bad' };
    default:
      return { label: 'Counted as reported', tone: 'neutral' };
  }
}

export function documentLabel(type: Gstr2bDocumentType): string {
  switch (type) {
    case Gstr2bDocumentType.CreditNote:
      return 'Credit note';
    case Gstr2bDocumentType.DebitNote:
      return 'Debit note';
    case Gstr2bDocumentType.Import:
      return 'Import';
    case Gstr2bDocumentType.IsdInvoice:
      return 'ISD credit';
    case Gstr2bDocumentType.IsdCreditNote:
      return 'ISD credit note';
    default:
      return 'Invoice';
  }
}

/** The tax on a reported line, in paise. */
export function lineTax(l: Gstr2bLineDto): number {
  return l.igstInPaise + l.cgstInPaise + l.sgstInPaise + l.cessInPaise;
}

