export class ArGstr2bPanel {
  private readonly api = inject(Gstr2bService);
  private readonly toasts = inject(ToastService);
  private readonly confirm = inject(ConfirmService);
  private readonly permissions = inject(PermissionService);

  /** MMYYYY. */
  readonly period = input.required<string>();
  /** The period's label, for messages. */
  readonly periodLabel = input('');
  /** The statement changed, so GSTR-3B should be read again. */
  readonly changed = output<void>();

  protected readonly Gstr2bLineMatch = Gstr2bLineMatch;
  protected readonly match = matchLabel;
  protected readonly docLabel = documentLabel;
  protected readonly tax = lineTax;
  protected readonly canImport = grantedPolicy(
    'AutoReach.GstCompliance.FileGstr',
    this.permissions,
  );

  readonly statement = signal<Gstr2bStatementDto | null>(null);
  readonly lines = signal<Gstr2bLineDto[]>([]);
  readonly total = signal(0);
  readonly missing = signal<Gstr2bMissingBillDto[]>([]);
  readonly filter = signal<Gstr2bLineMatch | null>(null);
  readonly loading = signal(true);
  readonly busy = signal(false);
  readonly error = signal<string | null>(null);

  protected readonly skippedText = computed(() => {
    const skipped = this.statement()?.skippedSections ?? {};
    const parts = Object.entries(skipped).map(
      ([section, count]) =>
        `${count} ${section === 'isd' ? 'ISD credit' : section.toUpperCase()} document(s)`,
    );
    return parts.length ? parts.join(', ') : null;
  });

  constructor() {
    effect(() => {
      const period = this.period();
      void this.load(period);
    });
  }

  async load(period = this.period()): Promise<void> {
    this.loading.set(true);
    this.error.set(null);
    this.filter.set(null);
    try {
      const [statement, missing] = await Promise.all([
        firstValueFrom(this.api.get(period, { skipHandleError: true })),
        firstValueFrom(this.api.getBillsMissing(period, { skipHandleError: true })),
      ]);
      if (period !== this.period()) return;
      this.statement.set(statement ?? null);
      this.missing.set(missing.items ?? []);
      if (statement) await this.loadLines(true);
      else {
        this.lines.set([]);
        this.total.set(0);
      }
    } catch (e) {
      if (period === this.period()) this.error.set(readApiError(e, 'GSTR-2B could not be loaded.'));
    } finally {
      if (period === this.period()) this.loading.set(false);
    }
  }

  private async loadLines(reset: boolean): Promise<void> {
    const period = this.period();
    const page = await firstValueFrom(
      this.api.getLines(
        {
          returnPeriod: period,
          match: this.filter() ?? undefined,
          skipCount: reset ? 0 : this.lines().length,
          maxResultCount: PAGE,
        },
        { skipHandleError: true },
      ),
    );
    if (period !== this.period()) return;
    const items = page.items ?? [];
    this.total.set(page.totalCount ?? items.length);
    this.lines.set(reset ? items : [...this.lines(), ...items]);
  }

  async setFilter(match: Gstr2bLineMatch | null): Promise<void> {
    this.filter.set(match);
    try {
      await this.loadLines(true);
    } catch (e) {
      this.error.set(readApiError(e, 'GSTR-2B could not be loaded.'));
    }
  }

  async more(): Promise<void> {
    this.busy.set(true);
    try {
      await this.loadLines(false);
    } catch (e) {
      this.error.set(readApiError(e, 'GSTR-2B could not be loaded.'));
    } finally {
      this.busy.set(false);
    }
  }

  async onFile(event: Event): Promise<void> {
    const field = event.target as HTMLInputElement;
    const file = field.files?.[0];
    field.value = '';
    if (!file || this.busy()) return;
    if (file.size > GSTR2B_MAX_BYTES) {
      this.error.set('That file is larger than 20 MB. Is it the GSTR-2B JSON for one month?');
      return;
    }

    this.busy.set(true);
    this.error.set(null);
    try {
      const json = await file.text();
      const result = await firstValueFrom(
        this.api.import(
          { returnPeriod: this.period(), fileName: file.name, json },
          { skipHandleError: true },
        ),
      );
      this.statement.set(result);
      this.toasts.success(
        `GSTR-2B imported: ${result.matched} matched, ${result.taxMismatch} with different tax, ${result.notInBooks} not in the books.`,
      );
      await this.load();
      this.changed.emit();
    } catch (e) {
      this.error.set(readApiError(e, 'The GSTR-2B could not be imported.'));
    } finally {
      this.busy.set(false);
    }
  }

  /** GSTR-2B came straight from the GST portal: the same follow-up as an upload. */
  async onPulled(result: Gstr2bStatementDto): Promise<void> {
    this.statement.set(result);
    this.toasts.success(
      `GSTR-2B pulled from the GST portal: ${result.matched} matched, ${result.taxMismatch} with different tax, ${result.notInBooks} not in the books.`,
    );
    await this.load();
    this.changed.emit();
  }

  async remove(): Promise<void> {
    const ok = await this.confirm.confirm({
      title: 'Remove this GSTR-2B?',
      message: `The GSTR-2B for ${this.periodLabel() || this.period()} will be removed, and the bills it matched go back to pending. GSTR-3B then counts bills marked matched by hand.`,
      confirmText: 'Remove',
      tone: 'danger',
    });
    if (!ok) return;
    this.busy.set(true);
    try {
      await firstValueFrom(this.api.delete(this.period(), { skipHandleError: true }));
      this.toasts.success('GSTR-2B removed.');
      await this.load();
      this.changed.emit();
    } catch (e) {
      this.error.set(readApiError(e, 'The GSTR-2B could not be removed.'));
    } finally {
      this.busy.set(false);
    }
  }
}
